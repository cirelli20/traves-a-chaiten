/* Cuaderno: 5 dobles páginas con efecto de hoja al avanzar y retroceder. */
(() => {
  'use strict';
  const libro=document.getElementById('libro-marco');if(!libro)return;
  const hojas=[...libro.querySelectorAll('.libro-hoja')];
  const anterior=document.getElementById('libro-anterior'),siguiente=document.getElementById('libro-siguiente');
  const contador=document.getElementById('libro-contador'),marcas=document.getElementById('avance-marcas');
  const irAlDiario=document.getElementById('libro-ir-diario');
  const reduce=window.matchMedia('(prefers-reduced-motion: reduce)');
  let actual=0,animando=false;
  hojas.forEach((_,i)=>{const m=document.createElement('i');if(i===0)m.className='activo';marcas.append(m)});
  function actualizar(){hojas.forEach((hoja,i)=>{hoja.hidden=i!==actual;hoja.classList.toggle('activa',i===actual)});anterior.disabled=actual===0||animando;siguiente.disabled=animando;siguiente.hidden=actual===hojas.length-1;irAlDiario.hidden=actual!==hojas.length-1;contador.textContent=`${String(actual+1).padStart(2,'0')} / ${String(hojas.length).padStart(2,'0')}`;[...marcas.children].forEach((n,i)=>n.classList.toggle('activo',i===actual));}
  function pasar(delta){
    const nuevo=actual+delta;if(animando||nuevo<0||nuevo>=hojas.length)return;
    const from=hojas[actual],to=hojas[nuevo];
    const caraAnterior=(delta>0 ? from.querySelector('.pagina-derecha') : to.querySelector('.pagina-derecha'));
    const caraPosterior=(delta>0 ? to.querySelector('.pagina-izquierda') : from.querySelector('.pagina-izquierda'));
    const movil=window.matchMedia('(max-width:650px)').matches;
    const trasera=movil?(delta>0 ? to.querySelector('.pagina-derecha') : from.querySelector('.pagina-derecha')):caraPosterior;
    const overlay=document.createElement('div');overlay.className=`libro-volteo ${delta>0?'siguiente':'anterior'}`;overlay.setAttribute('aria-hidden','true');
    for(const [className,source] of [['cara cara-front',caraAnterior],['cara cara-back',trasera]]){const face=document.createElement('div');face.className=className;face.append(source.cloneNode(true));overlay.append(face)}
    animando=true;actual=nuevo;actualizar();
    if(reduce.matches){animando=false;actualizar();return;}
    libro.append(overlay);
    overlay.addEventListener('animationend',()=>{overlay.remove();animando=false;actualizar();},{once:true});
  }
  anterior.addEventListener('click',()=>pasar(-1));siguiente.addEventListener('click',()=>pasar(1));
  document.addEventListener('keydown',ev=>{if(ev.altKey||ev.ctrlKey||ev.metaKey||/^(INPUT|TEXTAREA|SELECT)$/.test(document.activeElement?.tagName||''))return;if(ev.key==='ArrowRight'){if(actual===hojas.length-1&&!animando){irAlDiario.click();}else pasar(1);}if(ev.key==='ArrowLeft')pasar(-1);});
  actualizar();
})();


/* ===== DIARIO ===== */
/* Bitácora de doce jornadas.
 * Una escena por fotografía, varios comentarios por escena, y algunas notas ampliables.
 * Todo se edita en datos-bitacora.js; ningún texto de ejemplo es un testimonio real. */
(() => {
  'use strict';
  const datos=window.DATOS_TRAVESIA;
  if(!document.getElementById('diario-menu-dias')||!datos||!Array.isArray(datos.dias)||!datos.dias.length)return;
  const $=q=>document.querySelector(q);
  const esc=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const menu=$('#diario-menu-dias'),relato=$('#jornada-relato');
  const p=Number(new URLSearchParams(location.search).get('dia'));
  let activo=Number.isInteger(p)&&p>=1&&p<=datos.dias.length?p-1:0;
  let observer;
  const reducido=matchMedia('(prefers-reduced-motion: reduce)');

  // Recorrido fotográfico: la foto mantiene su proporción, sin zoom ni corte lateral.
  // El scroll atraviesa toda su altura; si sobra espacio, la foto se desplaza suavemente.
  const barraDias=$('#navegacion-dias');
  let escenas=[],cuadroPendiente=0,medirPendiente=false;
  function actualizarFotos(){
    cuadroPendiente=0;
    if(medirPendiente){
      medirPendiente=false;
      document.body.style.setProperty('--diario-barra',`${Math.ceil(barraDias.getBoundingClientRect().height)}px`);
      escenas.forEach(({escena,fondo,img})=>{
        const alto=img.naturalWidth?fondo.clientWidth*img.naturalHeight/img.naturalWidth:0;
        // Las imágenes altas reciben suficiente espacio de lectura para recorrerlas.
        escena.style.setProperty('--recorrido-foto',`${Math.ceil(alto+window.innerHeight*.65)}px`);
      });
    }
    escenas.forEach(({escena,fondo,img})=>{
      if(!img.naturalWidth)return;
      const alto=fondo.clientWidth*img.naturalHeight/img.naturalWidth;
      const ventana=fondo.clientHeight;
      const superior=parseFloat(getComputedStyle(fondo).top)||0;
      const rect=escena.getBoundingClientRect();
      const avance=Math.max(0,Math.min(1,(superior-rect.top)/Math.max(1,rect.height-ventana)));
      const diferencia=alto-ventana;
      // En fotos altas se revela desde el borde superior hasta el inferior.
      // En fotos apaisadas que ya caben, se mantiene completo el encuadre mientras se mueve.
      const y=diferencia>0?-diferencia*avance:(-diferencia)*(.65-.30*avance);
      img.style.setProperty('--foto-y',`${y.toFixed(2)}px`);
    });
  }
  function programarFotos(medir=false){
    medirPendiente=medirPendiente||medir;
    if(!cuadroPendiente)cuadroPendiente=requestAnimationFrame(actualizarFotos);
  }
  window.addEventListener('scroll',()=>programarFotos(),{passive:true});
  window.addEventListener('resize',()=>programarFotos(true),{passive:true});
  relato.addEventListener('load',e=>{if(e.target.tagName==='IMG')programarFotos(true)},true);
  const obsFotos='ResizeObserver' in window?new ResizeObserver(()=>programarFotos(true)):null;
  function prepararFotos(){
    obsFotos?.disconnect();
    escenas=[...relato.querySelectorAll('.escena-diario')].map(escena=>({escena,fondo:escena.querySelector('.escena-fondo'),img:escena.querySelector('.escena-fondo img')}));
    obsFotos?.observe(barraDias);
    escenas.forEach(({escena})=>obsFotos?.observe(escena));
    programarFotos(true);
  }

  datos.dias.forEach((dia,i)=>{
    const btn=document.createElement('button');
    btn.type='button';btn.innerHTML=`<span>DÍA</span><strong>${esc(dia.numero)}</strong>`;
    btn.setAttribute('aria-label',`Mostrar ${dia.etiqueta}`);
    btn.addEventListener('click',()=>mostrar(i,true));menu.append(btn);
  });
  $('#dia-atras').addEventListener('click',()=>mostrar(activo-1,true));
  $('#dia-adelante').addEventListener('click',()=>mostrar(activo+1,true));

  function escenaInfo(item,defaultSrc){
    if(typeof item==='string')return{src:item,alt:'Imagen de la jornada; sustituir por registro real.',pie:'REGISTRO POR INCORPORAR'};
    return{src:item?.src||item?.imagen||defaultSrc,alt:item?.alt||'Imagen provisional para documentar la jornada.',pie:item?.pie||'REGISTRO DE LA JORNADA'};
  }
  function imagenesDia(dia){
    const originales=Array.isArray(dia.imagenes)&&dia.imagenes.length?dia.imagenes:[dia.imagen,dia.imagen,dia.imagen,dia.imagen];
    return originales.map(item=>escenaInfo(item,dia.imagen||'assets/dias/dia-01.svg'));
  }
  function repartirNotas(notas,totalImagenes){
    const asignadas=Array.from({length:totalImagenes},()=>[]);
    notas.forEach((c,k)=>{
      // escena: 1, 2, 3... (opcional) vincula una nota a una fotografía específica.
      const n=Number(c.escena);
      const indice=c.escena!==undefined&&Number.isInteger(n)&&n>=1&&n<=totalImagenes?n-1:Math.min(totalImagenes-1,Math.floor(k*totalImagenes/Math.max(1,notas.length)));
      asignadas[indice].push({c,k});
    });
    return asignadas;
  }
  function tarjeta({c,k},diaNumero,orden){
    const color=['','roja','crema','oscura'][k%4];
    const etiqueta=c.categoria||'REGISTRO PENDIENTE';
    const detalle=Array.isArray(c.detalle)?c.detalle.filter(Boolean):(c.detalle?[c.detalle]:[]);
    const id=`detalle-${diaNumero}-${k}`;
    const extra=detalle.length?`<button class="voz-desplegar" type="button" aria-expanded="false" aria-controls="${id}"><span class="voz-boton-texto">Leer más</span><span class="voz-boton-simbolo" aria-hidden="true">+</span></button><div class="voz-detalle" id="${id}" hidden><span class="voz-detalle-titulo">AMPLIAR EL REGISTRO</span>${detalle.map(t=>`<p>${esc(t)}</p>`).join('')}${c.imagenDetalle?`<figure><img loading="lazy" src="${esc(c.imagenDetalle)}" alt="${esc(c.altDetalle||'Registro adicional de la jornada')}">${c.pieDetalle?`<figcaption>${esc(c.pieDetalle)}</figcaption>`:''}</figure>`:''}</div>`:'';
    return `<article class="voz-burbuja ${color}" data-revelar="1" style="--retardo:${Math.min(orden,3)*140}ms"><p class="voz-categoria">${esc(etiqueta)}</p><blockquote>“${esc(c.texto||'Testimonio por incorporar')}”</blockquote><div class="voz-autor"><strong>${esc(c.autor||'Participante por identificar')}</strong><span>VOZ ${String(k+1).padStart(2,'0')}</span></div>${extra}</article>`;
  }
  function contenidoEscena(asignadas,j,diaNumero){
    if(!asignadas.length)return '<span class="escena-sin-voces" data-revelar="1">Espacio para agregar comentarios sobre esta imagen.</span>';
    const grupos=[];
    // Se revelan en tramos diferentes del scroll. Cada pareja está en pantalla a la vez.
    for(let k=0;k<asignadas.length;k+=2){
      const par=asignadas.slice(k,k+2),g=grupos.length;
      const lado=['centro','derecha','izquierda','centro'][(j+g)%4];
      grupos.push(`<div class="voz-grupo" data-lado="${lado}" data-cantidad="${par.length}" aria-label="${par.length===2?'Dos comentarios de esta escena':'Comentario de esta escena'}">${par.map((nota,i)=>tarjeta(nota,diaNumero,i)).join('')}</div>`);
    }
    return grupos.join('');
  }
  function mostrar(i,desplazar){
    if(i<0||i>=datos.dias.length)return;
    activo=i;const dia=datos.dias[i];
    [...menu.children].forEach((btn,index)=>{
      btn.setAttribute('aria-pressed',String(i===index));
      if(index===i)btn.setAttribute('aria-current','step');else btn.removeAttribute('aria-current');
    });
    $('#contador-dias').textContent=`${dia.numero} / ${String(datos.dias.length).padStart(2,'0')}`;
    $('#jornada-etiqueta').textContent=`BITÁCORA / JORNADA ${dia.numero}`;
    $('#jornada-titulo').textContent=dia.titulo||dia.etiqueta;
    $('#jornada-resumen').textContent=dia.subtitulo||'Relato por completar.';
    $('#fecha-dia').textContent=dia.fecha||'FECHA POR COMPLETAR';
    $('#dia-atras').disabled=i===0;$('#dia-adelante').disabled=i===datos.dias.length-1;
    const fotos=imagenesDia(dia);
    const notas=Array.isArray(dia.comentarios)?dia.comentarios:[];
    const distribucion=repartirNotas(notas,fotos.length);
    relato.innerHTML=fotos.map((foto,j)=>`<section class="escena-diario" aria-label="Imagen ${j+1} de la jornada ${esc(dia.numero)}">
      <div class="escena-fondo"><img src="${esc(foto.src)}" alt="${esc(foto.alt)}" loading="${j===0?'eager':'lazy'}"><div class="escena-rotulo"><span>CHAITÉN · DÍA ${esc(dia.numero)}</span><span>${esc(foto.pie)}</span></div><div class="escena-contadores"><span>BITÁCORA VISUAL</span><span>${String(j+1).padStart(2,'0')} / ${String(fotos.length).padStart(2,'0')}</span></div></div>
      <div class="contenedor escena-contenido">${contenidoEscena(distribucion[j],j,dia.numero)}</div>
    </section>`).join('');
    prepararFotos();
    observer?.disconnect();
    if('IntersectionObserver'in window&&!reducido.matches){
      observer=new IntersectionObserver(entries=>{
        entries.forEach(entry=>{if(entry.isIntersecting){entry.target.classList.add('es-visible');observer.unobserve(entry.target)}});
      },{threshold:.12,rootMargin:'0px 0px -10% 0px'});
      relato.querySelectorAll('[data-revelar]').forEach(el=>observer.observe(el));
    }else relato.querySelectorAll('[data-revelar]').forEach(el=>el.classList.add('es-visible'));
    const btnActivo=menu.children[i];
    if(btnActivo&&desplazar)btnActivo.scrollIntoView({block:'nearest',inline:'center',behavior:reducido.matches?'instant':'smooth'});
    try{history.replaceState(null,'',`?dia=${i+1}`)}catch(_){/* Funciona también abriendo el HTML localmente. */}
    if(desplazar){
      const barra=$('#navegacion-dias').getBoundingClientRect().height;
      const header=parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--header'))||0;
      const to=$('#jornada').getBoundingClientRect().top+window.scrollY;
      window.scrollTo({top:Math.max(0,to-header-barra-10),behavior:reducido.matches?'instant':'smooth'});
    }
  }
  // Event delegation: los comentarios se reconstruyen cuando se cambia de día.
  relato.addEventListener('click',ev=>{
    const btn=ev.target.closest('.voz-desplegar');if(!btn)return;
    const detalle=document.getElementById(btn.getAttribute('aria-controls'));if(!detalle)return;
    const abrir=btn.getAttribute('aria-expanded')!=='true';
    btn.setAttribute('aria-expanded',String(abrir));detalle.hidden=!abrir;
    btn.querySelector('.voz-boton-texto').textContent=abrir?'Cerrar detalle':'Leer más';
    btn.querySelector('.voz-boton-simbolo').textContent=abrir?'−':'+';
    btn.closest('.voz-burbuja').classList.toggle('esta-abierta',abrir);
  });
  mostrar(activo,false);
})();

